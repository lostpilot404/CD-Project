def _first_sentence(text, limit=190):
    text = " ".join(text.split())
    if not text:
        return ""
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    sentence = match.group(1) if match else text
    if len(sentence) > limit:
        cut = sentence[:limit].rsplit(" ", 1)[0]
        sentence = cut.rstrip(",;:") + " …"
    return sentence


def _js_docstring(source):
    match = re.match(r"\s*/\*\*(.*?)\*/", source, re.S)
    if not match:
        return ""
    body = re.sub(r"^\s*\*\s?", "", match.group(1), flags=re.M)
    return body.replace("*/", "")


def purpose_of(relpath):
    relpath = relpath.replace(os.sep, "/")
    if relpath in PURPOSE_OVERRIDES:
        return PURPOSE_OVERRIDES[relpath]
    path = os.path.join(ROOT, relpath)
    try:
        with open(path, encoding="utf-8") as handle:
            source = handle.read()
    except (OSError, UnicodeDecodeError):
        return "binary asset"
    if relpath.endswith(".py"):
        try:
            doc = ast.get_docstring(ast.parse(source)) or ""
        except SyntaxError:
            doc = ""
        text = _first_sentence(doc)
        if not text and os.path.basename(relpath) == "__init__.py":
            return "package marker"
        return text
    if relpath.endswith(".md"):
        lines = [line.strip() for line in source.splitlines()]
        title = ""
        rest = []
        for line in lines:
            if not line:
                continue
            if not title and line.startswith("#"):
                title = line.lstrip("# ").strip()
                continue
            if title and not line.startswith(("#", "|", "-", "`", ">")):
                rest.append(line)
                if len(" ".join(rest)) > 60:
                    break
            elif title and rest:
                break
        text = _first_sentence(" ".join(rest)) if rest else ""
        if title and text:
            return f"{title} — {text}"
        return title or "documentation"
    if relpath.endswith(".js"):
        return _first_sentence(_js_docstring(source))
    if relpath.endswith(".ctc"):
        for line in source.splitlines():
            stripped = line.strip()
            if stripped.startswith("//"):
                text = stripped.lstrip("/").strip()
                if text.lower().startswith("expect:"):
                    text = "expects " + text[len("expect:"):].strip()
                else:
                    text = "example: " + text[:1].lower() + text[1:]
                if not text.endswith((".", "!", "?")):
                    text += "."
                return _first_sentence(text)
        return "labelled CT-C example"
    return ""


def _plain(text):
    return text.replace("**", "").replace("`", "").replace("*", "")


def inventory(paths, skip=()):
    """(relative path, lines, purpose) for every file under the given paths."""
    rows = []
    for entry in paths:
        absolute = os.path.join(ROOT, entry)
        if os.path.isfile(absolute):
            files = [entry]
        else:
            files = []
            for base, dirs, names in os.walk(absolute):
                dirs[:] = sorted(d for d in dirs if d != "__pycache__")
                for name in sorted(names):
                    full = os.path.join(base, name)
                    files.append(os.path.relpath(full, ROOT))
        for rel in sorted(files):
            if any(rel.startswith(prefix) for prefix in skip):
                continue
            if "__pycache__" in rel or rel.endswith(
                    (".png", ".pdf", ".pyc", ".docx", ".zip", ".jpg", ".ico")):
                continue
            with open(os.path.join(ROOT, rel), encoding="utf-8", errors="replace") as handle:
                lines = sum(1 for _ in handle)
            rel = rel.replace(os.sep, "/")
            rows.append((rel, lines, _plain(purpose_of(rel))))
    return rows


def package_total(rows):
    return len(rows), sum(line for _, line, _ in rows)


